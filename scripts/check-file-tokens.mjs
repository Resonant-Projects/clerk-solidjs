#!/usr/bin/env node
// Pre-commit check: block staged files over MAX_TOKENS estimated tokens.
//
// Tokens are estimated as bytes / 4, so the limit is 5,000 tokens = 20,000
// bytes. Only the staged blob of each file is measured (what the commit would
// contain), not the working-tree copy. Files git treats as binary, and the
// paths in IGNORE below, are skipped. Dependency-free; runs on plain Node.
//
//   node scripts/check-file-tokens.mjs        # check the index (used by husky)
//   MAX_FILE_TOKENS=8000 node scripts/...     # one-off override of the limit

import { execFileSync } from "node:child_process";

const MAX_TOKENS = Number(process.env.MAX_FILE_TOKENS) || 5000;
const BYTES_PER_TOKEN = 4;
const MAX_BYTES = MAX_TOKENS * BYTES_PER_TOKEN;

// ---------------------------------------------------------------------------
// Ignore list. Patterns use gitignore-style globs: `*` matches within one path
// segment, `**` matches across segments, and a pattern with no `/` matches the
// file name anywhere in the tree. Add a line here when a file is genuinely
// generated, vendored or otherwise not written by a person or an agent.
// ---------------------------------------------------------------------------
const IGNORE = [
  // Lockfiles
  "bun.lock",
  "bun.lockb",
  "package-lock.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "Cargo.lock",
  "poetry.lock",
  "uv.lock",
  "Gemfile.lock",
  "go.sum",
  "composer.lock",
  "flake.lock",

  // Generated / codegen output
  "convex/_generated/**",
  "**/generated/**",
  "*.gen.*",
  "routeTree.gen.ts",
  "worker-configuration.d.ts",
  "dist/**",
  "build/**",
  ".output/**",
  ".vinxi/**",

  // Binaries and assets (git's own binary detection also applies)
  "*.png",
  "*.jpg",
  "*.jpeg",
  "*.gif",
  "*.webp",
  "*.avif",
  "*.ico",
  "*.svg",
  "*.woff",
  "*.woff2",
  "*.ttf",
  "*.otf",
  "*.eot",
  "*.zip",
  "*.gz",
  "*.tar",
  "*.tgz",
  "*.7z",
  "*.rar",
  "*.db",
  "*.sqlite",
  "*.pdf",
  "*.mp4",
  "*.mov",
  "*.webm",
  "*.mp3",
  "*.wav",
  "*.ogg",

  // Minified output and test snapshots
  "*.min.*",
  "__snapshots__/**",

  // Repo-specific: generated by changesets and by
  // packages/clerk-solidjs/scripts/vendor-clerk-ui-types.mjs
  "CHANGELOG.md",
  "packages/clerk-solidjs/src/vendor/**",
];

const IGNORE_RE = IGNORE.map(globToRegExp);

function globToRegExp(glob) {
  let re = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*") {
      if (glob[i + 1] === "*") {
        i++;
        if (glob[i + 1] === "/") {
          i++;
          re += "(?:.*/)?"; // `**/` matches zero or more directories
        } else {
          re += ".*"; // trailing `**` matches the rest of the path
        }
      } else {
        re += "[^/]*";
      }
    } else if (c === "?") {
      re += "[^/]";
    } else {
      re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
    }
  }
  // A pattern with no slash matches a file name at any depth; one with a slash
  // may match from the repo root or from any subdirectory.
  return new RegExp(`(?:^|/)${re}$`, "s");
}

function isIgnored(file) {
  return IGNORE_RE.some((re) => re.test(file));
}

function git(args, input) {
  return execFileSync("git", args, { encoding: "utf8", input });
}

// Staged regular files as { file, blob }. Binary files (git's own detection,
// including .gitattributes), submodule gitlinks and symlinks are skipped.
// --no-renames makes every entry a plain path (renames become A + D).
function stagedTextFiles() {
  const common = ["diff", "--cached", "-z", "--no-renames", "--diff-filter=ACM"];

  // numstat: "added\tdeleted\tpath\0"; binary files report "-\t-". Paths are
  // emitted verbatim with -z, so split only at the first two tabs.
  const binary = new Set();
  for (const entry of git([...common, "--numstat"]).split("\0")) {
    if (!entry) continue;
    const first = entry.indexOf("\t");
    const second = entry.indexOf("\t", first + 1);
    const added = entry.slice(0, first);
    const deleted = entry.slice(first + 1, second);
    if (added === "-" && deleted === "-") binary.add(entry.slice(second + 1));
  }

  // raw: ":srcmode dstmode srcblob dstblob status\0path\0" per entry.
  const tokens = git([...common, "--raw", "--no-abbrev"]).split("\0");
  const files = [];
  for (let i = 0; i + 1 < tokens.length; i += 2) {
    const [, dstMode, , dstBlob] = tokens[i].split(" ");
    const file = tokens[i + 1];
    if (dstMode === "160000" || dstMode === "120000") continue; // gitlink, symlink
    if (binary.has(file)) continue;
    files.push({ file, blob: dstBlob });
  }
  return files;
}

function blobSize(blob) {
  return Number(git(["cat-file", "-s", blob]).trim());
}

function formatTokens(n) {
  return n.toLocaleString("en-US");
}

const offenders = [];
for (const { file, blob } of stagedTextFiles()) {
  if (isIgnored(file)) continue;
  const bytes = blobSize(blob);
  if (bytes > MAX_BYTES) {
    offenders.push({ file, bytes, tokens: Math.ceil(bytes / BYTES_PER_TOKEN) });
  }
}

if (offenders.length === 0) process.exit(0);

offenders.sort((a, b) => b.bytes - a.bytes);

const lines = [
  "",
  `✖ Commit blocked: ${offenders.length} staged file${offenders.length === 1 ? "" : "s"} exceed${offenders.length === 1 ? "s" : ""} the ${formatTokens(MAX_TOKENS)}-token limit (bytes / ${BYTES_PER_TOKEN}, so > ${formatTokens(MAX_BYTES)} bytes).`,
  "",
  ...offenders.map(
    ({ file, bytes, tokens }) =>
      `  ${file}  ~${formatTokens(tokens)} tokens (${formatTokens(bytes)} bytes)`,
  ),
  "",
  "Large files are hard for people and agents to read and edit. Split each one:",
  "  1. Split by responsibility: one module per concern, not one file per feature.",
  "  2. Move types, constants and small helpers into their own files",
  "     (e.g. foo.types.ts, foo.constants.ts, foo.utils.ts).",
  "  3. Extract components and sub-functions into sibling files and import them.",
  "  4. If callers import the old path, keep it as an index that re-exports",
  "     from the new files so nothing else has to change.",
  `  5. Keep every new file under ${formatTokens(MAX_TOKENS)} tokens (${formatTokens(MAX_BYTES)} bytes); check with:`,
  "       git cat-file -s :path/to/file",
  "",
  "Emergency bypass (please split in a follow-up):",
  "  git commit --no-verify",
  "",
  "If a file is genuinely generated or vendored, add its path to the IGNORE list",
  "in scripts/check-file-tokens.mjs instead of bypassing the hook.",
  "",
];

process.stderr.write(lines.join("\n"));
process.exit(1);
